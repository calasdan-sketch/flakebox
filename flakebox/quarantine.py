"""Quarantine appliers: turn the flaky set into something the runner obeys."""

from __future__ import annotations

import json
import os
import time

# The reason string the generated plugin attaches. junit.py looks for it
# to tell a quarantined-and-failed xfail apart from a hand-written xfail.
REASON = "quarantined: flaky per flakebox"
MODES = ("skip", "xfail")

PYTEST_PLUGIN = '''"""Generated by `flakebox quarantine --format pytest`.

Marks quarantined (flaky) tests via suffix-matching on node IDs, so it
works whether your JUnit IDs look like `pkg.mod.Class::test_x` or
`tests/test_mod.py::TestClass::test_x`.

Mode comes from flakebox_quarantine.json ("mode"):
  skip  - quarantined tests are skipped (default; they record no result)
  xfail - quarantined tests still run but cannot fail the build; their
          real pass/fail still lands in the JUnit report, so flakebox can
          see them stabilise and tell you to un-quarantine them

Usage: drop this file + flakebox_quarantine.json in your repo root and run:
    pytest -p flakebox_quarantine
Regenerate after `flakebox unquarantine` changes the set.
"""
import json
import os

import pytest

_HERE = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(_HERE, "flakebox_quarantine.json"),
          encoding="utf-8") as _f:
    _DATA = json.load(_f)
QUARANTINED = _DATA["tests"]
MODE = _DATA.get("mode", "skip")
REASON = "quarantined: flaky per flakebox"


def _matches(nodeid: str, q: str) -> bool:
    # Compare the trailing Class::test segments (module::test for
    # classless tests), ignoring the module prefix: JUnit IDs
    # (`pkg.mod.Class::test_x`) and pytest node IDs
    # (`tests/test_mod.py::TestClass::test_x`) rarely agree on it.
    # The `.py` suffix (and any path) is stripped BEFORE the trailing
    # dot-split so classless node IDs (`test_mod.py::test_x`) match
    # JUnit IDs (`test_mod::test_x`, `pkg.test_mod::test_x`).
    # (Same class+test name in two modules will both match - v1 tradeoff.)
    def tail(seg: str) -> str:
        for sep in ("/", chr(92)):  # drop any path (posix or windows)
            seg = seg.split(sep)[-1]
        if seg.endswith(".py"):
            seg = seg[:-len(".py")]
        return seg.split(".")[-1]
    n = [tail(s) for s in nodeid.split("::")]
    m = [tail(s) for s in q.split("::")]
    return len(n) >= 2 and len(m) >= 2 and n[-2:] == m[-2:]


def _marker():
    if MODE == "xfail":
        return pytest.mark.xfail(reason=REASON, strict=False)
    return pytest.mark.skip(reason=REASON)


def pytest_collection_modifyitems(items):
    for item in items:
        if any(_matches(item.nodeid, q) for q in QUARANTINED):
            item.add_marker(_marker())
'''


def write_pytest(out_dir: str, test_ids: list[str],
                 mode: str = "skip") -> list[str]:
    if mode not in MODES:
        raise ValueError(f"mode must be one of {MODES}, got {mode!r}")
    os.makedirs(out_dir, exist_ok=True)
    written = []
    jp = os.path.join(out_dir, "flakebox_quarantine.json")
    with open(jp, "w", encoding="utf-8") as f:
        json.dump({"tests": sorted(set(test_ids)),
                   "mode": mode,
                   "generated_at": int(time.time()),
                   "count": len(set(test_ids))}, f, indent=2)
        f.write("\n")
    written.append(jp)
    pp = os.path.join(out_dir, "flakebox_quarantine.py")
    with open(pp, "w", encoding="utf-8") as f:
        f.write(PYTEST_PLUGIN)
    written.append(pp)
    return written


def deselect_args(test_ids: list[str]) -> list[str]:
    """Best-effort `--deselect` args. IDs are JUnit-style; pytest node IDs
    usually share the suffix, so this works more often than not - but the
    generated plugin (--format pytest) is the reliable path."""
    args = []
    for tid in sorted(set(test_ids)):
        args += ["--deselect", tid]
    return args
