"""Quarantine appliers: turn the flaky set into something the runner obeys."""

from __future__ import annotations

import json
import os
import shlex
import subprocess

# The reason string the generated plugin attaches. junit.py looks for it
# to tell a quarantined-and-failed xfail apart from a hand-written xfail.
REASON = "quarantined: flaky per flakebox"
MODES = ("skip", "xfail")

PYTEST_PLUGIN = '''"""Generated by `flakebox quarantine --format pytest`.

Marks the quarantined (flaky) tests. A test is quarantined when it has the
same name (with any [parameters]) as a quarantined id and the same module
path and class names, compared as whole components in either spelling: the
pytest node id `tests/test_mod.py::TestA::test_x` and the JUnit id
`tests.test_mod.TestA::test_x` are the same test. Only leading directories
may be missing from one side (CI and your machine can have different
rootdirs): `test_mod.py::test_x` matches `tests.test_mod::test_x`, but
`pkg_a/test_mod.py::test_x` never matches `pkg_b/test_mod.py::test_x`.

Mode comes from flakebox_quarantine.json ("mode"):
  skip  - quarantined tests are skipped (default; they record no result)
  xfail - quarantined tests still run but cannot fail the build; their
          real pass/fail still lands in the JUnit report, so flakebox can
          see them stabilise and tell you to un-quarantine them

Usage: drop this file + flakebox_quarantine.json in your repo root and run
    python -m pytest -p flakebox_quarantine
`python -m pytest` puts the current directory on sys.path; the bare
`pytest` command does not, so it cannot import this file (if the plugin
lives in another directory, put that directory on PYTHONPATH).
Regenerate after `flakebox unquarantine` changes the set.

Quarantine is never silent: the end of every run lists the quarantined
tests it skipped (or ran as xfail) with their owner and expiry. An entry
with an `expires_at` stops applying once it has passed - the test runs
again and can fail the build - even if this file was never regenerated.
"""
import json
import os
import time

import pytest

_HERE = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(_HERE, "flakebox_quarantine.json"),
          encoding="utf-8") as _f:
    _DATA = json.load(_f)
QUARANTINED = _DATA["tests"]
MODE = _DATA.get("mode", "skip")
ENTRIES = _DATA.get("entries", {})  # id -> {owner, expires_at, reason}
REASON = "quarantined: flaky per flakebox"


def _key(test_id):
    """(name, chain) of a JUnit id or a pytest node id, or None.

    name is the test function plus its [parameters]; chain is the module
    path and the class names as whole components, so `pkg/mod.py::A::t`
    and `pkg.mod.A::t` both give ("t", ("pkg", "mod", "A")). An id with no
    module part gives None: it would match every test of that name.
    """
    # split off the parameters first: they may contain `::`, `/` and `.`
    base, bracket, params = test_id.partition("[")
    parts = base.replace(chr(92), "/").split("::")
    if len(parts) < 2:
        return None
    head = parts[0]
    if head.endswith(".py"):
        head = head[:-3]
    chain = []
    for part in [head.replace("/", ".")] + parts[1:-1]:
        chain.extend(piece for piece in part.split(".") if piece)
    if not chain:
        return None
    return parts[-1] + bracket + params, tuple(chain)


def _index(ids):
    exact, tails = {}, {}
    for test_id in ids:
        key = _key(test_id)
        if key is not None:
            name, chain = key
            exact.setdefault(key, test_id)
            for i in range(len(chain)):
                tails.setdefault((name, chain[i:]), test_id)
    return exact, tails


# every quarantined (name, chain), and every tail of a quarantined chain,
# each mapped to the quarantined id it came from
_EXACT, _TAILS = _index(QUARANTINED)


def _match(nodeid):
    """The quarantined id that `nodeid` is, or None."""
    key = _key(nodeid)
    if key is None:
        return None
    name, chain = key
    # this chain is a tail of a quarantined one (the id was recorded with
    # more leading directories) ...
    if key in _TAILS:
        return _TAILS[key]
    # ... or a quarantined chain is a tail of this one (it has fewer)
    for i in range(len(chain)):
        hit = _EXACT.get((name, chain[i:]))
        if hit is not None:
            return hit
    return None


def _is_quarantined(nodeid):
    return _match(nodeid) is not None


def _expired(test_id):
    expires = (ENTRIES.get(test_id) or {}).get("expires_at")
    return expires is not None and expires <= time.time()


def _marker():
    if MODE == "xfail":
        return pytest.mark.xfail(reason=REASON, strict=False)
    return pytest.mark.skip(reason=REASON)


_APPLIED = []      # (nodeid, quarantined id) the plugin marked
_EXPIRED = set()   # quarantined ids whose expiry had passed: they ran


def pytest_collection_modifyitems(items):
    for item in items:
        qid = _match(item.nodeid)
        if qid is None:
            continue
        if _expired(qid):
            _EXPIRED.add(qid)    # the quarantine ended: the test runs
            continue
        item.add_marker(_marker())
        _APPLIED.append((item.nodeid, qid))


def _clean(text):
    """Printable characters only: an id or an owner can come from an
    imported file, and a terminal obeys the control characters in it."""
    return "".join(c if c.isprintable() else "?" for c in str(text))


def _until(qid):
    entry = ENTRIES.get(qid) or {}
    bits = []
    if entry.get("owner"):
        bits.append("owner " + _clean(entry["owner"]))
    if entry.get("expires_at") is not None:
        left = (entry["expires_at"] - time.time()) / 86400
        bits.append("expires in %d day(s)" % int(left + 0.999)
                    if left > 0 else "expired")
    return " (" + ", ".join(bits) + ")" if bits else ""


def pytest_terminal_summary(terminalreporter):
    """Quarantine is never silent."""
    if not (_APPLIED or _EXPIRED):
        return
    out = terminalreporter
    out.write_sep("=", "flakebox quarantine")
    if _APPLIED:
        how = "ran as xfail" if MODE == "xfail" else "were skipped"
        out.write_line("%d test(s) %s because they are quarantined as "
                       "flaky:" % (len(_APPLIED), how))
        for nodeid, qid in sorted(_APPLIED)[:50]:
            out.write_line("  " + nodeid + _until(qid))
        if len(_APPLIED) > 50:
            out.write_line("  ... and %d more" % (len(_APPLIED) - 50))
    for qid in sorted(_EXPIRED):
        out.write_line("EXPIRED quarantine - ran again and can fail the "
                       "build: " + _clean(qid) + _until(qid))
        out.write_line("  fix it, or: flakebox renew --test <id> --days N")
'''


def write_pytest(out_dir: str, test_ids: list[str],
                 mode: str = "skip", entries: dict | None = None) -> list[str]:
    if mode not in MODES:
        raise ValueError(f"mode must be one of {MODES}, got {mode!r}")
    os.makedirs(out_dir, exist_ok=True)
    written = []
    jp = os.path.join(out_dir, "flakebox_quarantine.json")
    ids = sorted(set(test_ids))
    with open(jp, "w", encoding="utf-8") as f:
        # no timestamp: regenerating an unchanged set writes the same bytes
        doc = {"tests": ids, "mode": mode, "count": len(ids)}
        kept = {t: e for t, e in sorted((entries or {}).items())
                if t in set(ids) and e}
        if kept:    # owner / expiry, only when there are any
            doc["entries"] = kept
        json.dump(doc, f, indent=2)
        f.write("\n")
    written.append(jp)
    pp = os.path.join(out_dir, "flakebox_quarantine.py")
    with open(pp, "w", encoding="utf-8") as f:
        f.write(PYTEST_PLUGIN)
    written.append(pp)
    return written


def pytest_nodeid(test_id: str) -> str:
    """Map a JUnit id to the pytest node id it most likely came from.

    pytest writes classname = dotted module path + class names and
    name = the function (with any [params]). Modules are lowercase by
    convention and classes start with a capital, so the leading run of
    segments that do not start with an uppercase letter is the module:

        pkg.module.Class::test_x    -> pkg/module.py::Class::test_x
        pkg.module.Outer.Inner::t   -> pkg/module.py::Outer::Inner::t
        pkg.module::test_x          -> pkg/module.py::test_x
        test_x (no classname)       -> test_x (unchanged)

    Best effort: a lowercase class name, a `python_files` pattern that
    is not `*.py`, or a non-pytest producer breaks the guess, and pytest
    simply ignores a --deselect that matches nothing. The generated
    plugin (--format pytest) compares the name and the whole path
    components instead and is the reliable path. Ids already in node-id
    form (containing `/` or `.py::`) pass through unchanged.
    """
    if "::" not in test_id or "/" in test_id or ".py::" in test_id:
        return test_id
    classname, _, rest = test_id.partition("::")
    segs = [s for s in classname.split(".") if s]
    if not segs:
        return test_id
    i = 0
    while i < len(segs) and not segs[i][:1].isupper():
        i += 1
    module, classes = segs[:i], segs[i:]
    if not module:  # classname is just class names: no module to place
        return "::".join(classes + [rest])
    return "::".join(["/".join(module) + ".py"] + classes + [rest])


def deselect_args(test_ids: list[str]) -> list[str]:
    """`--deselect` args for pytest, with JUnit ids mapped to pytest node
    ids by pytest_nodeid() (best effort - see there)."""
    args = []
    for tid in sorted(set(test_ids)):
        args += ["--deselect", pytest_nodeid(tid)]
    return args


def deselect_line(test_ids: list[str]) -> str:
    """deselect_args() as one shell line. Each argument is quoted for the
    local shell (POSIX quoting via shlex, cmd.exe double-quoting on
    Windows), so the shell has to parse the line once more -
    `eval "pytest $(flakebox quarantine --format deselect)"` - to hand
    pytest an id with a space or shell characters (`test_x[a b]`,
    `test_x[$HOME]`) as ONE argument. A bare `pytest $(...)` splits the
    output at whitespace and keeps the quotes, so only ids with neither
    survive it (the README also covers PowerShell)."""
    args = deselect_args(test_ids)
    if os.name == "nt":
        return subprocess.list2cmdline(args)
    return shlex.join(args)


# ---------------------------------------------------------------------------
# other runners: each returns (arguments, left_out). `left_out` are the ids
# the runner cannot express; they keep RUNNING (and can fail the build) -
# quarantine never widens to hide a test nobody asked to hide.
# ---------------------------------------------------------------------------

_REGEX_SPECIAL = frozenset("\\.+*?()|[]{}^$")


def _regex_escape(text: str) -> str:
    """Escape for a JavaScript or Go (RE2) regular expression."""
    return "".join("\\" + c if c in _REGEX_SPECIAL else c for c in text)


def _shell_line(args: list[str]) -> str:
    if os.name == "nt":
        return subprocess.list2cmdline(args)
    return shlex.join(args)


def jest_name(test_id: str) -> str:
    """The Jest test name inside a JUnit id. jest-junit (its default
    templates) writes the FULL name (describe blocks + test title, joined
    by spaces) as both the classname and the name: `cart adds::cart
    adds`. When the two halves are equal the name is one of them; any
    other shape is taken as `classname::name`."""
    n = len(test_id)
    for i in range(n):
        if test_id.startswith("::", i):
            left, right = test_id[:i], test_id[i + 2:]
            if left == right:
                return left
    return test_id.rpartition("::")[2]


def jest_args(test_ids: list[str]) -> tuple[list[str], list[str]]:
    """`--testNamePattern=^(?!(?:name1|name2)$)`: Jest runs every test
    whose full name is NOT one of the quarantined ones, and reports the
    others as skipped (they are counted, not hidden)."""
    names = sorted({jest_name(t) for t in test_ids if t})
    if not names:
        return [], []
    alt = "|".join(_regex_escape(n) for n in names)
    return [f"--testNamePattern=^(?!(?:{alt})$)"], []


def go_args(test_ids: list[str]) -> tuple[list[str], list[str]]:
    """`-skip '^(?:TestA|TestB)$'` (Go 1.20+). The go tool matches the
    pattern against test names without the package, and allows one -skip,
    so only top-level tests can be listed: a subtest id (`TestA/case`) is
    left out and keeps running."""
    names, left_out = set(), []
    for t in sorted(set(test_ids)):
        name = t.rpartition("::")[2]
        if not name or "/" in name or not name.isidentifier():
            left_out.append(t)
        else:
            names.add(name)
    if not names:
        return [], left_out
    alt = "|".join(sorted(names))
    return ["-skip", f"^(?:{alt})$"], left_out


def maven_args(test_ids: list[str]) -> tuple[list[str], list[str]]:
    """`-Dtest=!pkg.Class#method,...` (Maven Surefire 2.19+ exclusion
    syntax). A name that is not a plain method name (a parameterised case
    such as `test[1]`) cannot be excluded alone and is left out."""
    parts, left_out = [], []
    for t in sorted(set(test_ids)):
        cls, sep, name = t.rpartition("::")
        name = name[:-2] if name.endswith("()") else name
        ok = (bool(sep) and bool(cls) and bool(name)
              and name.replace("_", "a").replace("$", "a").isalnum()
              and all(c.isalnum() or c in "._$" for c in cls))
        if ok:
            parts.append(f"!{cls}#{name}")
        else:
            left_out.append(t)
    return ([f"-Dtest={','.join(parts)}"] if parts else []), left_out


RUNNER_FORMATS = {"jest": jest_args, "go": go_args, "maven": maven_args}


def runner_line(fmt: str, test_ids: list[str]) -> tuple[str, list[str]]:
    """(shell line, left_out) for `--format jest|go|maven`."""
    args, left_out = RUNNER_FORMATS[fmt](test_ids)
    return _shell_line(args), left_out
