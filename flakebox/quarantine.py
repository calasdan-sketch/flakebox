"""Quarantine appliers: turn the flaky set into something the runner obeys."""

from __future__ import annotations

import json
import os
import shlex
import subprocess
import time

# The reason string the generated plugin attaches. junit.py looks for it
# to tell a quarantined-and-failed xfail apart from a hand-written xfail.
REASON = "quarantined: flaky per flakebox"
MODES = ("skip", "xfail")
DAY = 86400


def expired(entries: list[dict], days: int | None,
            now: float | None = None) -> list[dict]:
    """The quarantined tests (store.quarantined() rows) older than `days`
    days, oldest first, each with its age in whole days: [{"test_id",
    "days"}]. `days` None is off. A quarantine with no date (an old
    database) has no age and never expires."""
    if days is None:
        return []
    now = time.time() if now is None else now
    out = [{"test_id": e["test_id"], "days": int((now - e["at"]) // DAY),
            "_at": e["at"]}
           for e in entries
           if e.get("at") is not None and now - e["at"] > days * DAY]
    out.sort(key=lambda x: (x["_at"], x["test_id"]))
    for x in out:
        del x["_at"]
    return out

PYTEST_PLUGIN = '''"""Generated by `flakebox quarantine --format pytest`.

Marks the quarantined (flaky) tests. A test is quarantined when it has the
same name (with any [parameters]) as a quarantined id and the same module
path and class names, compared as whole components in either spelling: the
pytest node id `tests/test_mod.py::TestA::test_x` and the JUnit id
`tests.test_mod.TestA::test_x` are the same test. Only leading directories
may be missing from one side (CI and your machine can have different
rootdirs): `test_mod.py::test_x` matches `tests.test_mod::test_x`, but
`pkg_a/test_mod.py::test_x` never matches `pkg_b/test_mod.py::test_x`.

Mode comes from flakebox_quarantine.json ("mode"):
  skip  - quarantined tests are skipped (default; they record no result)
  xfail - quarantined tests still run but cannot fail the build; their
          real pass/fail still lands in the JUnit report, so flakebox can
          see them stabilise and tell you to un-quarantine them

Usage: drop this file + flakebox_quarantine.json in your repo root and run
    python -m pytest -p flakebox_quarantine
`python -m pytest` puts the current directory on sys.path; the bare
`pytest` command does not, so it cannot import this file (if the plugin
lives in another directory, put that directory on PYTHONPATH).
Regenerate after `flakebox unquarantine` changes the set.
"""
import json
import os

import pytest

_HERE = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(_HERE, "flakebox_quarantine.json"),
          encoding="utf-8") as _f:
    _DATA = json.load(_f)
QUARANTINED = _DATA["tests"]
MODE = _DATA.get("mode", "skip")
REASON = "quarantined: flaky per flakebox"


def _key(test_id):
    """(name, chain) of a JUnit id or a pytest node id, or None.

    name is the test function plus its [parameters]; chain is the module
    path and the class names as whole components, so `pkg/mod.py::A::t`
    and `pkg.mod.A::t` both give ("t", ("pkg", "mod", "A")). An id with no
    module part gives None: it would match every test of that name.
    """
    # split off the parameters first: they may contain `::`, `/` and `.`
    base, bracket, params = test_id.partition("[")
    parts = base.replace(chr(92), "/").split("::")
    if len(parts) < 2:
        return None
    head = parts[0]
    if head.endswith(".py"):
        head = head[:-3]
    chain = []
    for part in [head.replace("/", ".")] + parts[1:-1]:
        chain.extend(piece for piece in part.split(".") if piece)
    if not chain:
        return None
    return parts[-1] + bracket + params, tuple(chain)


def _index(ids):
    exact, tails = set(), set()
    for test_id in ids:
        key = _key(test_id)
        if key is not None:
            name, chain = key
            exact.add(key)
            tails.update((name, chain[i:]) for i in range(len(chain)))
    return exact, tails


# every quarantined (name, chain), and every tail of a quarantined chain
_EXACT, _TAILS = _index(QUARANTINED)


def _is_quarantined(nodeid):
    key = _key(nodeid)
    if key is None:
        return False
    name, chain = key
    # this chain is a tail of a quarantined one (the id was recorded with
    # more leading directories) ...
    if key in _TAILS:
        return True
    # ... or a quarantined chain is a tail of this one (it has fewer)
    return any((name, chain[i:]) in _EXACT for i in range(len(chain)))


def _marker():
    if MODE == "xfail":
        return pytest.mark.xfail(reason=REASON, strict=False)
    return pytest.mark.skip(reason=REASON)


def pytest_collection_modifyitems(items):
    for item in items:
        if _is_quarantined(item.nodeid):
            item.add_marker(_marker())
'''


def write_pytest(out_dir: str, test_ids: list[str],
                 mode: str = "skip") -> list[str]:
    if mode not in MODES:
        raise ValueError(f"mode must be one of {MODES}, got {mode!r}")
    os.makedirs(out_dir, exist_ok=True)
    written = []
    jp = os.path.join(out_dir, "flakebox_quarantine.json")
    ids = sorted(set(test_ids))
    with open(jp, "w", encoding="utf-8") as f:
        # no timestamp: regenerating an unchanged set writes the same bytes
        json.dump({"tests": ids, "mode": mode, "count": len(ids)}, f, indent=2)
        f.write("\n")
    written.append(jp)
    pp = os.path.join(out_dir, "flakebox_quarantine.py")
    with open(pp, "w", encoding="utf-8") as f:
        f.write(PYTEST_PLUGIN)
    written.append(pp)
    return written


def pytest_nodeid(test_id: str) -> str:
    """Map a JUnit id to the pytest node id it most likely came from.

    pytest writes classname = dotted module path + class names and
    name = the function (with any [params]). Modules are lowercase by
    convention and classes start with a capital, so the leading run of
    segments that do not start with an uppercase letter is the module:

        pkg.module.Class::test_x    -> pkg/module.py::Class::test_x
        pkg.module.Outer.Inner::t   -> pkg/module.py::Outer::Inner::t
        pkg.module::test_x          -> pkg/module.py::test_x
        test_x (no classname)       -> test_x (unchanged)

    Best effort: a lowercase class name, a `python_files` pattern that
    is not `*.py`, or a non-pytest producer breaks the guess, and pytest
    simply ignores a --deselect that matches nothing. The generated
    plugin (--format pytest) compares the name and the whole path
    components instead and is the reliable path. Ids already in node-id
    form (containing `/` or `.py::`) pass through unchanged.
    """
    if "::" not in test_id or "/" in test_id or ".py::" in test_id:
        return test_id
    classname, _, rest = test_id.partition("::")
    segs = [s for s in classname.split(".") if s]
    if not segs:
        return test_id
    i = 0
    while i < len(segs) and not segs[i][:1].isupper():
        i += 1
    module, classes = segs[:i], segs[i:]
    if not module:  # classname is just class names: no module to place
        return "::".join(classes + [rest])
    return "::".join(["/".join(module) + ".py"] + classes + [rest])


def deselect_args(test_ids: list[str]) -> list[str]:
    """`--deselect` args for pytest, with JUnit ids mapped to pytest node
    ids by pytest_nodeid() (best effort - see there)."""
    args = []
    for tid in sorted(set(test_ids)):
        args += ["--deselect", pytest_nodeid(tid)]
    return args


def deselect_line(test_ids: list[str]) -> str:
    """deselect_args() as one shell line. Each argument is quoted for the
    local shell (POSIX quoting via shlex, cmd.exe double-quoting on
    Windows), so the shell has to parse the line once more -
    `eval "pytest $(flakebox quarantine --format deselect)"` - to hand
    pytest an id with a space or shell characters (`test_x[a b]`,
    `test_x[$HOME]`) as ONE argument. A bare `pytest $(...)` splits the
    output at whitespace and keeps the quotes, so only ids with neither
    survive it (the README also covers PowerShell)."""
    args = deselect_args(test_ids)
    if os.name == "nt":
        return subprocess.list2cmdline(args)
    return shlex.join(args)


# --- other runners (best effort) -------------------------------------------
# These turn the quarantine set into a command-line option for runners that
# have no plugin of ours. They match by TEST NAME only, so two tests that
# share a name in different files are both skipped, and a renamed test is not.

_JS_SPECIAL = set("\\.*+?^${}()|[]/")
_RE2_SPECIAL = set("\\.*+?^${}()|[]")


def _escape(text: str, special: set) -> str:
    return "".join("\\" + c if c in special else c for c in text)


def _quote_args(args: list[str]) -> str:
    return subprocess.list2cmdline(args) if os.name == "nt" else shlex.join(args)


def js_names(test_ids: list[str], vitest: bool = False) -> list[str]:
    """Full test names (describe blocks and test title joined by a space, the
    text `-t` matches) from jest-junit ids (`full name::full name`) or
    vitest ids (`file::suite > test`)."""
    names = set()
    for tid in test_ids:
        left, sep, right = tid.partition("::")
        if vitest:
            name = (right if sep else left).replace(" > ", " ")
        else:
            name = left
        name = name.strip()
        if name:
            names.add(name)
    return sorted(names)


def _not_these(names: list[str], special: set) -> str:
    alt = "|".join(_escape(n, special) for n in names)
    return f"^(?!(?:{alt})$)"


def jest_line(test_ids: list[str], vitest: bool = False) -> str:
    """`--testNamePattern '<regex>'` (jest) or `-t '<regex>'` (vitest) that
    runs everything EXCEPT the quarantined names: a negative lookahead on
    the full test name. Empty when nothing is quarantined."""
    names = js_names(test_ids, vitest)
    if not names:
        return ""
    flag = "-t" if vitest else "--testNamePattern"
    return _quote_args([flag, _not_these(names, _JS_SPECIAL)])


def go_names(test_ids: list[str]) -> tuple[list[str], int]:
    """(top-level test names, number of subtests that could not be
    expressed). `go test -skip` takes ONE pattern split on `/` per level, so
    a list of subtests under different parents cannot be written; their
    parents are not skipped (that would hide the healthy subtests)."""
    top, subs = set(), 0
    for tid in test_ids:
        name = tid.partition("::")[2] if "::" in tid else tid
        name = name.strip()
        if not name:
            continue
        if "/" in name:
            subs += 1
        else:
            top.add(name)
    return sorted(top), subs


def go_line(test_ids: list[str]) -> str:
    """`-skip '^(TestA|TestB)$'` for `go test` (Go 1.20 or newer)."""
    names, _ = go_names(test_ids)
    if not names:
        return ""
    alt = "|".join(_escape(n, _RE2_SPECIAL) for n in names)
    return _quote_args(["-skip", f"^({alt})$"])
